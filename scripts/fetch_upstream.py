"""Fetch the third-party reference files listed in tests/upstream/MANIFEST.json.

The files are not part of the repository. Their tests skip until this script has fetched
them; each one is checked against the size and sha256 in the manifest. The Intl.NumberFormat
reference is not downloaded but generated by Node (scripts/intl_reference.mjs); it only
matches the manifest with the Node version the manifest names.

    python scripts/fetch_upstream.py
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "tests" / "upstream"


def _download(url: str) -> bytes:
    # Some hosts refuse the default urllib agent.
    request = urllib.request.Request(url, headers={"User-Agent": "indgroup-fetch"})
    with urllib.request.urlopen(request, timeout=60) as response:
        body: bytes = response.read()
    return body


def main() -> int:
    manifest = json.loads((FOLDER / "MANIFEST.json").read_text(encoding="utf-8"))
    failed = 0
    for name, entry in manifest.items():
        target = FOLDER / name
        if "generate" in entry:
            done = subprocess.run(entry["generate"], cwd=ROOT, check=False)
            body = target.read_bytes() if done.returncode == 0 and target.is_file() else b""
        else:
            body = _download(entry["url"])
        digest = hashlib.sha256(body).hexdigest()
        if len(body) != entry["size"] or digest != entry["sha256"]:
            print(f"{name}: got {len(body)} bytes, sha256 {digest}; manifest differs")
            target.unlink(missing_ok=True)
            failed += 1
            continue
        target.write_bytes(body)
        print(f"{name}: ok")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
